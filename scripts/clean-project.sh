#!/usr/bin/env bash
# DORA — safe project cleanup.
#
# Removes only regenerable local artefacts: build output, caches, debug logs, OS metadata and
# iCloud conflict copies. Never touches source code, migrations, tests, assets, documentation,
# .env files, Docker images/volumes, database data or Git history (no docker or git write
# commands are run). Any candidate containing Git-tracked files is skipped.
#
# Usage: bash scripts/clean-project.sh [--dry-run | --apply] [--deep]
#   --dry-run  (default) list what would be removed, remove nothing
#   --apply    remove the listed items
#   --deep     additionally node_modules/ and src/generated/prisma/ (restore with `npm ci`)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

if [[ ! -f package.json || ! -f Dockerfile || ! -d prisma/migrations ]]; then
  echo "Error: DORA project root not recognized ($ROOT)." >&2
  exit 1
fi

MODE="--dry-run"
DEEP=false
for arg in "$@"; do
  case "$arg" in
    --dry-run | --apply) MODE="$arg" ;;
    --deep) DEEP=true ;;
    -h | --help)
      sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
      exit 0
      ;;
    *)
      echo "Usage: bash scripts/clean-project.sh [--dry-run | --apply] [--deep]" >&2
      exit 1
      ;;
  esac
done

HAS_GIT=false
if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then HAS_GIT=true; fi

COUNT=0
SKIPPED=0

# True if the path is, or contains, a file tracked by Git.
is_tracked() {
  [[ "$HAS_GIT" == true ]] && [[ -n "$(git ls-files -- "$1" 2>/dev/null | head -n 1)" ]]
}

# Never remove these, whatever a pattern matched.
is_protected() {
  case "$1" in
    .env | .env.* | */.env | */.env.*) return 0 ;;
    prisma | prisma/* | assets | assets/* | tests | tests/* | docker | docker/* | public | public/*) return 0 ;;
    *.md | Dockerfile | compose.yaml | package.json | package-lock.json) return 0 ;;
  esac
  return 1
}

remove() {
  local path="${1#./}" reason="$2"
  [[ -e "$path" || -L "$path" ]] || return 0
  if is_protected "$path"; then
    echo "[SKIP protected] $path"
    SKIPPED=$((SKIPPED + 1))
    return 0
  fi
  if is_tracked "$path"; then
    echo "[SKIP tracked]   $path"
    SKIPPED=$((SKIPPED + 1))
    return 0
  fi
  local size
  size="$(du -sh "$path" 2>/dev/null | cut -f1 | tr -d ' ')"
  if [[ "$MODE" == "--apply" ]]; then
    rm -rf -- "$path"
    echo "[REMOVED]        $path ($size) — $reason"
  else
    echo "[WOULD REMOVE]   $path ($size) — $reason"
  fi
  COUNT=$((COUNT + 1))
}

echo "DORA project cleanup"
echo "Mode: $MODE$([[ "$DEEP" == true ]] && echo " + --deep")"
echo "Root: $ROOT"
echo

# 1. Build output and tool caches (all regenerated by build/test/dev commands).
for target in \
  .next .next.nosync out coverage test-results playwright-report \
  .turbo .cache .eslintcache \
  node_modules/.cache node_modules/.vite; do
  remove "$target" "build output / cache"
done

# 2. OS metadata, debug logs and TypeScript build info (tsconfig.tsbuildinfo) anywhere in the tree.
while IFS= read -r -d '' file; do
  remove "$file" "OS metadata / debug log"
done < <(
  find . \( -path ./.git -o -path ./node_modules -o -path ./.next -o -path ./.next.nosync \) -prune -o \
    -type f \( -name .DS_Store -o -name Thumbs.db -o -name '*.tsbuildinfo' \
      -o -name 'npm-debug.log*' -o -name 'yarn-debug.log*' -o -name 'yarn-error.log*' \
      -o -name '.pnpm-debug.log*' \) -print0
)

# 3. iCloud conflict copies ("name 2.ext" / "name 2"). Removed only when the original exists and
#    the copy is identical to it, or when the copy lies in generated output; anything else is
#    reported for manual review, because a conflict copy may hold real changes.
while IFS= read -r -d '' copy; do
  copy="${copy#./}"
  dir="$(dirname "$copy")"
  name="$(basename "$copy")"
  if [[ "$name" == *" 2."* ]]; then
    original="$dir/${name/ 2./.}"
  else
    original="$dir/${name% 2}"
  fi
  original="${original#./}"
  if is_tracked "$copy"; then
    echo "[SKIP tracked]   $copy"
    SKIPPED=$((SKIPPED + 1))
  elif [[ "$copy" == src/generated/* ]]; then
    remove "$copy" "iCloud conflict copy in generated code"
  elif [[ -e "$original" ]] && diff -rq -- "$original" "$copy" >/dev/null 2>&1; then
    remove "$copy" "iCloud conflict copy identical to $original"
  else
    echo "[REVIEW]         $copy — possible iCloud conflict copy that differs from (or lacks) $original; not removed"
    SKIPPED=$((SKIPPED + 1))
  fi
done < <(
  find . \( -path ./.git -o -path ./node_modules \) -prune -o \( -name '* 2' -o -name '* 2.*' \) -print0
)

# 4. Optional: installed dependencies and the generated Prisma client (restore with `npm ci`).
if [[ "$DEEP" == true ]]; then
  remove node_modules "dependencies (--deep; restore with npm ci)"
  remove src/generated/prisma "generated Prisma client (--deep; restored by npm ci / prisma generate)"
fi

echo
if [[ "$MODE" == "--apply" ]]; then
  echo "Removed $COUNT item(s); skipped $SKIPPED."
else
  echo "$COUNT item(s) would be removed; $SKIPPED skipped. Run with --apply to remove them."
fi
echo "Not touched: source code, migrations, tests, assets, documentation, .env files,"
echo "Docker images and volumes, database data, Git history."
